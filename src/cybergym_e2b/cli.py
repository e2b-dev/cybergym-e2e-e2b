def _common(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--upstream", type=Path, default=DEFAULT_UPSTREAM)
    parser.add_argument("--keys-file", type=Path, default=DEFAULT_KEYS_FILE)


def _run_options(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--network-policy", type=Path, default=DEFAULT_NETWORK_POLICY)
    parser.add_argument(
        "--image-lock",
        "--image-map",
        dest="image_map",
        type=Path,
        default=DEFAULT_IMAGE_LOCK,
        help="complete digest lock generated by `cybergym-e2b images lock`",
    )
    parser.add_argument("--patch-file", type=Path, default=DEFAULT_PATCH_FILE)
    parser.add_argument("--remote-smoke", type=Path, default=DEFAULT_REMOTE_SMOKE)
    parser.add_argument("--remote-install-codex", type=Path, default=DEFAULT_REMOTE_INSTALL_CODEX)
    parser.add_argument("--artifacts-dir", type=Path, default=Path("artifacts/e2e"))
    parser.add_argument("--setup-timeout", type=int, default=7200)
    parser.add_argument("--evaluation-timeout", type=int, default=28800)
    parser.add_argument("--min-free-gb", type=int, default=80)
    parser.add_argument("--ffmpeg-min-free-gb", type=int, default=90)
    parser.add_argument(
        "--swap-gb",
        type=int,
        default=4,
        help="disk-backed swap inside each sandbox; keeps the 8-GB RAM shape viable for spikes",
    )
    parser.add_argument(
        "--egress",
        choices=["policy", "restricted", "permissive"],
        default="policy",
        help=(
            "enforce the selected policy (default), use the legacy restricted allowlist, "
            "or disable policy egress filters for diagnostics"
        ),
    )
    parser.add_argument("--retain", action="store_true")


def _agent_options(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--agent", choices=["codex", "openhands", "gemini-cli"], default="codex")
    parser.add_argument("--prompt-style", choices=["iterative", "no-test"], default="iterative")
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument(
        "--reasoning-effort",
        choices=["low", "medium", "high", "xhigh"],
        default="high",
        help="explicit Codex reasoning effort; high matches this security workload",
    )
    parser.add_argument("--max-attempts", type=int, default=1)
    parser.add_argument("--agent-timeout", type=int, default=5400)
    parser.add_argument(
        "--provider",
        choices=["fireworks", "bedrock"],
        default=DEFAULT_MODEL_PROVIDER,
        help="model API provider; Bedrock uses its OpenAI-compatible Mantle endpoint",
    )
    parser.add_argument("--bedrock-region", default="us-west-2")


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="cybergym-e2b")
    sub = parser.add_subparsers(dest="command", required=True)

    sync = sub.add_parser("sync-upstream", help="clone and verify the pinned CyberGym-E2E code")
    sync.add_argument("--upstream", type=Path, default=DEFAULT_UPSTREAM)

    inv = sub.add_parser("inventory", help="resolve all task/image relationships")
    inv.add_argument("--upstream", type=Path, default=DEFAULT_UPSTREAM)
    inv.add_argument("--output", type=Path, default=Path("artifacts/inventory.json"))

    images = sub.add_parser("images", help="manage immutable project-image identities")
    images_sub = images.add_subparsers(dest="image_command", required=True)
    image_lock = images_sub.add_parser("lock", help="resolve every mutable upstream image")
    image_lock.add_argument("--upstream", type=Path, default=DEFAULT_UPSTREAM)
    image_lock.add_argument("--output", type=Path, default=DEFAULT_IMAGE_LOCK)

    templates = sub.add_parser("templates", help="build shared E2B templates")
    templates_sub = templates.add_subparsers(dest="template_command", required=True)
    base = templates_sub.add_parser("build-base")
    _common(base)
    base.add_argument("--name", default=DEFAULT_TEMPLATE_NAME)
    base.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    base.add_argument("--ledger", type=Path, default=DEFAULT_BUILD_LEDGER)
    base.add_argument("--requirements", type=Path, default=DEFAULT_TEMPLATE_REQUIREMENTS)
    base.add_argument("--cpu-count", type=int, default=8)
    base.add_argument("--memory-mb", type=int, default=8192)
    base.add_argument("--disk-limit-gb", type=int, default=120)
    ffmpeg = templates_sub.add_parser("build-ffmpeg")
    _common(ffmpeg)
    ffmpeg.add_argument("--name", default=DEFAULT_FFMPEG_TEMPLATE_NAME)
    ffmpeg.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    ffmpeg.add_argument("--ledger", type=Path, default=DEFAULT_BUILD_LEDGER)

    preflight = sub.add_parser("preflight", help="verify checkout, manifest, keys, and HF access")
    _common(preflight)
    preflight.add_argument("--task", default="curl/arvo_66012")
    preflight.add_argument("--kind", choices=["run", "smoke"], default="run")
    _run_options(preflight)
    _agent_options(preflight)

    smoke = sub.add_parser("smoke", help="compile one task and run ground-truth stage 4")
    _common(smoke)
    smoke.add_argument("task", nargs="?", default="curl/arvo_66012")
    _run_options(smoke)

    run = sub.add_parser("run", help="run upstream CyberGym-E2E for one task")
    _common(run)
    run.add_argument("task")
    _run_options(run)
    _agent_options(run)

    batch = sub.add_parser("batch", help="run one E2B sandbox per task with bounded concurrency")
    _common(batch)
    batch.add_argument("--tasks-file", type=Path)
    batch.add_argument(
        "--kind",
        choices=["run", "smoke"],
        default="run",
        help="run agents or infrastructure-only ground-truth compile smokes",
    )
    batch.add_argument("--concurrency", type=int, default=40)
    batch.add_argument("--limit", type=int)
    batch.add_argument("--continue-on-error", action=argparse.BooleanOptionalAction, default=True)
    batch.add_argument(
        "--reuse-completed",
        "--resume",
        dest="reuse_completed",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="reuse only exact-fingerprint completed artifacts (default)",
    )
    _run_options(batch)
    _agent_options(batch)
    return parser


def _verify_upstream(path: Path) -> str:
    if not (path / ".git").is_dir():
        raise FileNotFoundError(f"pinned checkout is missing: {path}; run sync-upstream")
    commit = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=path, check=True, capture_output=True, text=True
    ).stdout.strip()
    if commit != UPSTREAM_COMMIT:
        raise RuntimeError(f"upstream checkout is {commit}, expected {UPSTREAM_COMMIT}")
    return commit


def _sync(path: Path) -> dict:
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", UPSTREAM_REPOSITORY, str(path)], check=True)
    if not (path / ".git").is_dir():
        raise RuntimeError(f"refusing to replace non-git path: {path}")
    status = subprocess.run(
        ["git", "status", "--porcelain"], cwd=path, check=True, capture_output=True, text=True
    ).stdout.strip()
    if status:
        raise RuntimeError(f"refusing to change dirty managed checkout: {path}")
    subprocess.run(["git", "fetch", "origin", UPSTREAM_COMMIT], cwd=path, check=True)
    subprocess.run(["git", "checkout", "--detach", UPSTREAM_COMMIT], cwd=path, check=True)
    return {"repository": UPSTREAM_REPOSITORY, "commit": _verify_upstream(path), "path": str(path)}


def _options(args: argparse.Namespace) -> RunOptions:
    options = RunOptions(
        setup_timeout=args.setup_timeout,
        evaluation_timeout=args.evaluation_timeout,
        min_free_gb=args.min_free_gb,
        ffmpeg_min_free_gb=args.ffmpeg_min_free_gb,
        swap_gb=args.swap_gb,
        egress=args.egress,
        retain=args.retain,
    )
    # Agent flags exist only on `run`/`batch`; fall back to RunOptions defaults for `smoke`.
    agent_overrides = {
        field: getattr(args, field)
        for field in (
            "agent",
            "prompt_style",
            "model",
            "reasoning_effort",
            "max_attempts",
            "agent_timeout",
            "provider",
            "bedrock_region",
        )
        if hasattr(args, field)
    }
    return replace(options, **agent_overrides)


def _execute(
    args: argparse.Namespace,
    task: str,
    *,
    kind: str,
    batch_id: str | None = None,
    resolved: ResolvedTask | None = None,
    experiment: dict | None = None,
) -> dict:
    if resolved is None:
        image_map = load_image_map(args.image_map, upstream=args.upstream)
        resolved = resolve_task(args.upstream, task, image_map=image_map)
    require_immutable_runtime_image(resolved)
    return execute_task(
        resolved,
        kind=kind,
        upstream=args.upstream,
        artifacts_dir=args.artifacts_dir,
        options=_options(args),
        manifest_path=args.manifest,
        network_policy_path=args.network_policy,
        patch_file=args.patch_file,
        remote_smoke=args.remote_smoke,
        remote_install_codex=args.remote_install_codex,
        batch_id=batch_id,
        experiment=experiment,
    )


def _tasks(args: argparse.Namespace) -> list[str]:
    path = args.tasks_file or (args.upstream / "scripts/tasks.txt")
    tasks = [
        line.strip()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    return tasks[: args.limit] if args.limit else tasks


def _already_completed(artifacts_dir: Path, task: str, experiment_sha256: str) -> bool:
    """Reuse only a completed result for the exact requested experiment.

    A malformed patch or a compile failure is a legitimate failed model result,
    not an infrastructure retry. Ground-truth smoke runs are retried when their
    validation stage itself errored, because those contain no model output.
    """
    project, _, task_id = task.partition("/")
    for result_path in (artifacts_dir / project / task_id).glob("*/result.json"):
        try:
            result = json.loads(result_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        if result.get("completed") is not True:
            continue
        if (result.get("experiment") or {}).get("sha256") != experiment_sha256:
            continue
        benchmark = result.get("benchmark") or {}
        if benchmark.get("status") not in {"passed", "failed"}:
            continue
        if benchmark.get("status") == "failed" and benchmark.get("agent") == "codex":
            turn = benchmark.get("agent_turn") or _codex_turn_state(result_path.parent)
            if turn.get("status") != "completed":
                continue
        smoke_stages = benchmark.get("stages") or {}
        if "error" not in smoke_stages.values():
            return True
    return False


def _batch(args: argparse.Namespace) -> dict:
    if not 1 <= args.concurrency <= 180:
        raise ValueError("concurrency must be between 1 and 180")
    requested = _tasks(args)
    image_map = load_image_map(args.image_map, upstream=args.upstream)
    options = _options(args)
    manifest = TemplateManifest.load(args.manifest)
    work: list[tuple[str, ResolvedTask, dict]] = []
    for task in requested:
        resolved = resolve_task(args.upstream, task, image_map=image_map)
        require_immutable_runtime_image(resolved)
        experiment = _experiment_identity(
            resolved,
            kind=args.kind,
            upstream=args.upstream,
            options=options,
            manifest_path=args.manifest,
            network_policy_path=args.network_policy,
            patch_file=args.patch_file,
            remote_smoke=args.remote_smoke,
            remote_install_codex=args.remote_install_codex,
            manifest=manifest,
        )
        if args.reuse_completed and _already_completed(
            args.artifacts_dir, task, experiment["sha256"]
        ):
            continue
        work.append((task, resolved, experiment))
    skipped = len(requested) - len(work)
    batch_id = uuid.uuid4().hex
    summary: dict = {
        "batch_id": batch_id,
        "kind": args.kind,
        "requested": len(requested),
        "skipped_completed": skipped,
        "submitted": len(work),
        "concurrency": args.concurrency,
        "artifact_reuse": args.reuse_completed,
        "results": [],
    }
    with ThreadPoolExecutor(max_workers=args.concurrency) as pool:
        futures = {
            pool.submit(
                _execute,
                args,
                task,
                kind=args.kind,
                batch_id=batch_id,
                resolved=resolved,
                experiment=experiment,
            ): task
            for task, resolved, experiment in work
        }
        cancel_requested = False
        for future in as_completed(futures):
            task = futures[future]
            try:
                result = future.result()
            except CancelledError as exc:
                result = {
                    "task": task,
                    "completed": False,
                    "canceled": True,
                    "error": {"type": type(exc).__name__, "message": str(exc)},
                }
            except Exception as exc:
                result = {
                    "task": task,
                    "completed": False,
                    "error": {"type": type(exc).__name__, "message": str(exc)},
                }
            summary["results"].append(result)
            print(
                json.dumps(
                    {
                        "task": task,
                        "infrastructure_completed": result.get("completed"),
                        "benchmark_status": result.get("benchmark", {}).get("status"),
                        "error": result.get("error"),
                    }
                ),
                flush=True,
            )
            if result.get("error") and not args.continue_on_error and not cancel_requested:
                cancel_requested = True
                for pending in futures:
                    if pending is not future:
                        pending.cancel()
    summary["infrastructure_completed"] = sum(
        bool(item.get("completed")) for item in summary["results"]
    )
    summary["infrastructure_failures"] = (
        len(summary["results"]) - summary["infrastructure_completed"]
    )
    summary["canceled"] = sum(bool(item.get("canceled")) for item in summary["results"])
    summary["benchmark_passed"] = sum(
        item.get("benchmark", {}).get("status") == "passed" for item in summary["results"]
    )
    summary["benchmark_exact_matches"] = sum(
        item.get("benchmark", {}).get("outcome") == "exact_match" for item in summary["results"]
    )
    summary["benchmark_other_vulnerabilities"] = sum(
        item.get("benchmark", {}).get("outcome") == "valid_other_vulnerability"
        for item in summary["results"]
    )
    summary["benchmark_not_passed"] = (
        summary["infrastructure_completed"] - summary["benchmark_passed"]
    )
    output = args.artifacts_dir / "batches" / f"{batch_id}.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    summary["summary_path"] = str(output)
    return summary


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if args.command == "sync-upstream":
            result = _sync(args.upstream)
        elif args.command == "inventory":
            _verify_upstream(args.upstream)
            inventory_result = inventory(args.upstream)
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(
                json.dumps(inventory_result, indent=2, sort_keys=True) + "\n", encoding="utf-8"
            )
            result = {
                key: inventory_result[key]
                for key in (
                    "tasks",
                    "projects",
                    "unique_build_images",
                    "single_use_build_images",
                )
            }
            result["output"] = str(args.output)
        elif args.command == "images":
            commit = _verify_upstream(args.upstream)
            lock = write_image_lock(args.upstream, args.output)
            result = {
                "output": str(args.output),
                "upstream_commit": commit,
                "mutable_images": len(lock["images"]),
                "resolver": lock["resolver"],
            }
        elif args.command == "templates":
            load_env_file(args.keys_file)
            if args.template_command == "build-base":
                manifest = build_base_template(
                    requirements=args.requirements,
                    name=args.name,
                    manifest_path=args.manifest,
                    ledger_path=args.ledger,
                    cpu_count=args.cpu_count,
                    memory_mb=args.memory_mb,
                    disk_limit_gb=args.disk_limit_gb,
                )
            else:
                manifest = build_ffmpeg_template(
                    manifest_path=args.manifest,
                    ledger_path=args.ledger,
                    name=args.name,
                )
            result = {
                "base": manifest.base.reference,
                "hot": {image: ref.reference for image, ref in manifest.hot.items()},
                "manifest": str(args.manifest),
            }
        elif args.command == "preflight":
            loaded = load_env_file(args.keys_file)
            commit = _verify_upstream(args.upstream)
            resolved = resolve_task(
                args.upstream,
                args.task,
                image_map=load_image_map(args.image_map, upstream=args.upstream),
            )
            options = _options(args)
            context = _execution_context(
                resolved,
                options=options,
                manifest_path=args.manifest,
                network_policy_path=args.network_policy,
            )
            hf_token = os.environ.get("HF_TOKEN") or os.environ.get("HUGGING_FACE_HUB_TOKEN")
            hf = preflight_access(resolved.task, hf_token)
            e2b_key_present = bool(os.environ.get("E2B_API_KEY"))
            model_key_present = bool(context.model_config["key"])
            template_verification: dict
            if e2b_key_present:
                try:
                    template_verification = {"ok": True, **verify_template_ref(context.template)}
                except Exception as exc:
                    template_verification = {
                        "ok": False,
                        "error": {"type": type(exc).__name__, "message": str(exc)},
                    }
            else:
                template_verification = {"ok": False, "reason": "E2B_API_KEY is missing"}
            credentials_ok = args.kind == "smoke" or model_key_present
            result = {
                "ok": e2b_key_present
                and hf["ok"]
                and credentials_ok
                and template_verification["ok"],
                "upstream_commit": commit,
                "kind": args.kind,
                "task": resolved.task,
                "build_image": resolved.build_image,
                "runtime_image": resolved.runtime_image,
                "template": {
                    "reference": context.template.reference,
                    "template_id": context.template.template_id,
                    "build_id": context.template.build_id,
                    "recipe_sha256": context.template.recipe_sha256,
                },
                "template_verification": template_verification,
                "network_eligibility": _network_eligibility(context.policy, options.egress),
                "keys_loaded": sorted(loaded),
                "e2b_api_key_present": e2b_key_present,
                "selected_model_key": {
                    "name": context.model_config["key_name"],
                    "present": model_key_present,
                    "required": args.kind == "run",
                },
                "fireworks_key_present": bool(
                    os.environ.get("FIREWORKS_AI_API_KEY") or os.environ.get("FIREWORKS_API_KEY")
                ),
                "bedrock_key_present": bool(
                    os.environ.get("AWS_MANTLE") or os.environ.get("AWS_BEARER_TOKEN_BEDROCK")
                ),
                "hugging_face": hf,
            }
        elif args.command in {"smoke", "run", "batch"}:
            load_env_file(args.keys_file)
            _verify_upstream(args.upstream)
            if not os.environ.get("E2B_API_KEY"):
                raise RuntimeError("E2B_API_KEY is missing")
            if args.command == "batch":
                result = _batch(args)
            else:
                result = _execute(args, args.task, kind=args.command)
        else:
            return 2
    except Exception as exc:
        print(
            json.dumps({"error": {"type": type(exc).__name__, "message": str(exc)}}),
            file=sys.stderr,
        )
        return 1
    print(json.dumps(result, indent=2, sort_keys=True))
    if args.command == "preflight" and not result.get("ok"):
        return 1
    if args.command == "batch" and result.get("infrastructure_failures"):
        return 1
    return 1 if result.get("error") else 0


if __name__ == "__main__":
    raise SystemExit(main())
